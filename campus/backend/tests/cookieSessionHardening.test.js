'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..','..');
const front=fs.readFileSync(path.join(root,'frontend','index.html'),'utf8');
const appRuntime=fs.readFileSync(path.join(root,'frontend','app-runtime.js'),'utf8');
const frontendSource=front+'\n'+appRuntime;
const sync=fs.readFileSync(path.join(root,'frontend','cloud-sync.js'),'utf8');
const auth=fs.readFileSync(path.join(root,'backend','src','routes','auth.js'),'utf8');
const portalAuth=fs.readFileSync(path.join(root,'backend','src','routes','portalAuth.js'),'utf8');
assert(!/localStorage\.(?:getItem|setItem)\(\s*['"]CP_ACCESS_TOKEN['"]/.test(frontendSource),'Access JWT must never be read/written from localStorage');
assert(!/localStorage\.(?:getItem|setItem)\(\s*['"]CP_ACCESS_TOKEN['"]/.test(sync),'Cloud sync must never persist the access JWT');
assert(/credentials:\s*['"]include['"]/.test(frontendSource),'Frontend API requests must include cookies');
assert(/httpOnly\s*:\s*true/.test(auth) && /httpOnly:true/.test(portalAuth),'Access/refresh cookies must be HttpOnly');
assert(/res\.json\(\{\s*user:\s*publicUser/.test(auth),'Core auth must not return the access JWT to browser JavaScript');
assert(/res\.json\(\{user:publicUser/.test(portalAuth),'Portal auth must not return the access JWT to browser JavaScript');
assert(!/res\.json\(\{[^\n]*accessToken/.test(auth),'No auth response may expose accessToken in JSON');
assert(!/res\.json\(\{[^\n]*accessToken/.test(portalAuth),'No portal auth response may expose accessToken in JSON');
console.log('Cookie-session hardening checks passed.');
